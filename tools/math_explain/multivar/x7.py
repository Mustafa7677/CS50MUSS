K = 0.45  # қиғаш проекция


def P(x, y, z):
    return (y - K * x, z - K * x)


def axes(n=5.5):
    o = P(0, 0, 0)
    return [seg(*o, *P(n, 0, 0), arrow=True), seg(*o, *P(0, n, 0), arrow=True), seg(*o, *P(0, 0, n * 0.9), arrow=True),
            txt(*P(n + 0.6, 0, 0), "x"), txt(*P(0, n + 0.3, 0), "y"), txt(*P(0, 0.2, n * 0.9 + 0.1), "z")]


def box(a, b, c):
    v = [P(x, y, z) for x in (0, a) for y in (0, b) for z in (0, c)]
    E = [(0, 1), (0, 2), (0, 4), (1, 3), (1, 5), (2, 3), (2, 6), (3, 7), (4, 5), (4, 6), (5, 7), (6, 7)]
    return [seg(*v[i], *v[j], c=1) for i, j in E]



COUNTS = [len(s[7]) for s in SUBJECTS]
STARTS = []
_acc = 0
for _c in COUNTS:
    STARTS.append(_acc)
    _acc += _c


def locate(n):
    """week-N -> (пән индексі 0.., пән ішіндегі сабақ нөмірі 0..)"""
    for i, st in enumerate(STARTS):
        if n < st + COUNTS[i]:
            return i, n - st
    raise IndexError(n)


def unit_label(n):
    i, k = locate(n)
    s = SUBJECTS[i]
    return f"{s[0]} · {s[2]} · {k + 1}-сабақ"


def week_name(subject_no, lesson_no):
    """(пән 1.., сабақ 1..) -> 'week-N'"""
    return f"week-{STARTS[subject_no - 1] + lesson_no - 1}"



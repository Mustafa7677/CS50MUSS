def stats(exists):
    """exists(href) -> bool. Әр бағыттың дайын/жоспар модульдері (беттегі сандар осыдан)."""
    out = {}
    for t in TRACKS:
        ready = total = 0
        for g in t["grades"].values():
            for _, href, _ in g["mods"]:
                total += 1
                ready += 1 if href and exists(href) else 0
        out[t["id"]] = (ready, total)
    return out

def b(ch, say, *do, mood=None, ask=None):
    r = {"ch": ch, "say": say, "do": [list(d) for d in do]}
    if mood:
        r["mood"] = mood
    if ask:
        r["ask"] = {"q": ask[0], "opts": ask[1], "ans": ask[2], "why": ask[3]}
    return r


def story(hook, props, beats, key, trap, hookSay=None):
    s = {"hook": hook, "props": props, "beats": beats, "key": key, "trap": {"wrong": trap[0], "right": trap[1]}}
    if hookSay:
        s["hookSay"] = hookSay
    return s



def _plain(h):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", h or ""))).strip()


def _sentences(t):
    return [s for s in re.split(r"(?<=[.?!])\s+", t) if s]


def _first(t, limit):
    out = ""
    for s in _sentences(t):
        if len(out) + len(s) + 1 > limit:
            break
        out = (out + " " + s).strip()
    return out or (t[:limit - 1].rsplit(" ", 1)[0] + "…" if len(t) > limit else t)


def auto(L):
    steps = L["derivation"]
    n = len(steps)
    xs = [70 + i * (500 / max(1, n - 1)) for i in range(n)]
    ys = [205 if i % 2 == 0 else 120 for i in range(n)]
    props = [text("ttl", 320, 40, L["title"], size=22, tone="dim")]
    for i in range(n):
        if i:
            x0, y0, x1, y1 = round(xs[i - 1]), ys[i - 1], round(xs[i]), ys[i]
            mx = (x0 + x1) / 2
            props.append(path(f"r{i}", f"M{x0} {y0}C{mx:.0f} {y0} {mx:.0f} {y1} {x1} {y1}", tone="dim"))
    props += [node(f"n{i}", round(xs[i]), ys[i], str(i + 1), r=22, tone="acc") for i in range(n)]
    props.append(chip("mk", round(xs[0]), ys[0] - 46, "★", tone="gold"))
    concept = _plain(L["concept"])
    hook_stage = _first(concept, 110) if len(_sentences(concept)[0]) <= 110 else L["title"]
    beats = []
    for i, s in enumerate(steps):
        do = [(SH, "ttl", f"n{i}", "mk"), (MV, "mk", round(xs[i]), ys[i] - 46), (HL, f"n{i}")]
        if i:
            do += [(SH, f"r{i}"), (UN, f"n{i - 1}")]
        beats.append(b("Жол", f"{i + 1}-қадам. {s}", *do, mood="happy" if i == n - 1 else None))
    mc = next((x for x in L["exercises"] + L["assessment"] if x["type"] == "mc"), None)
    if mc:
        why = mc["why"][mc["answer"]] if isinstance(mc.get("why"), list) else mc.get("why", "")
        beats.append(b("Тексер", "", (UN, f"n{n - 1}"), ask=(mc["q"], mc["options"], mc["answer"], why)))
    th = next((t for t in L["theory"] if t["kind"] == "theorem"), None) or next((t for t in L["theory"] if t["kind"] == "definition"), L["theory"][0])
    body = _first(_plain(th["body"]), 170)
    key = f"{th['title']}. {body}" if body and len(body) <= 170 else th["title"]
    m = L["mistakes"][0]
    return story(hook_stage, props, beats, key, (m["mistake"], m["fix"]), hookSay=_first(concept, 260))


def for_lesson(L):
    s = STORIES.get(L["id"])
    if s:
        return dict(s, kind="авторлық")
    return dict(auto(L), kind="авто")


def transcript(s):
    """Сценарийдің толық мәтіні (JS жоқ кезде және экран оқу құралдары үшін)."""
    rows = [("Сұрақ", s.get("hookSay") or s["hook"])]
    for bt in s["beats"]:
        if bt.get("ask"):
            rows.append((bt["ch"], bt["ask"]["q"] + " Жауап: " + bt["ask"]["opts"][bt["ask"]["ans"]] + ". " + bt["ask"]["why"]))
        if bt["say"]:
            rows.append((bt["ch"], bt["say"]))
    rows.append(("Түйін", s["key"]))
    if s.get("trap"):
        rows.append(("Түйін", f"Жиі қате: {s['trap']['wrong']} Дұрысы: {s['trap']['right']}"))
    return rows


def validate(lid, s):
    errs = []
    ids = [p["id"] for p in s["props"]]
    if len(set(ids)) != len(ids):
        errs.append(f"{lid} cine: реквизит id қайталанады")
    known = set(ids) | {"_hook", "_key", "_bad", "_good"}
    for p in s["props"]:
        if p["type"] not in TYPES:
            errs.append(f"{lid} cine: белгісіз түр {p['type']}")
        if p.get("tone", "") not in TONES:
            errs.append(f"{lid} cine: белгісіз реңк {p.get('tone')}")
        if p["type"] == "edge" and not (p["a"] in known and p["b"] in known):
            errs.append(f"{lid} cine: edge {p['id']} түйіні жоқ")
        if "x" in p and not (0 <= p["x"] <= W and 0 <= p["y"] <= H):
            errs.append(f"{lid} cine: {p['id']} сахнадан тыс ({p['x']}, {p['y']})")
        if p["type"] == "box" and p.get("t") and p.get("lab", "below") == "below" and p["y"] + p["h"] + p.get("size", 22) + 6 > H - 4:
            errs.append(f"{lid} cine: {p['id']} атауы сахнаның астынан шығып кетеді")
        if p["type"] == "box" and (p["x"] + p["w"] > W or p["y"] + p["h"] > H):
            errs.append(f"{lid} cine: {p['id']} қорап сахнадан шығып кетеді")
        if p["type"] == "chip" and (p["x"] - (len(p["t"]) * p.get("size", 22) * 0.56 + 26) / 2 < -2 or p["x"] + (len(p["t"]) * p.get("size", 22) * 0.56 + 26) / 2 > W + 2):
            errs.append(f"{lid} cine: {p['id']} белгісі сахнаға сыймайды")
    if not s["beats"]:
        errs.append(f"{lid} cine: көрініс жоқ")
    asks = 0
    for i, bt in enumerate(s["beats"]):
        if not bt["say"] and not bt.get("ask"):
            errs.append(f"{lid} cine: {i}-көріністе мәтін жоқ")
        for d in bt["do"]:
            if d[0] not in OPS:
                errs.append(f"{lid} cine: белгісіз әрекет {d[0]}")
            elif d[0] in ("show", "hide", "hl", "un", "dim"):
                errs += [f"{lid} cine: {d[0]} -> жоқ реквизит {x}" for x in d[1:] if x not in known]
            elif d[0] not in ("dimall", "clear") and d[1] not in known:
                errs.append(f"{lid} cine: {d[0]} -> жоқ реквизит {d[1]}")
            if d[0] == "move" and not (0 <= d[2] <= W and 0 <= d[3] <= H):
                errs.append(f"{lid} cine: move сахнадан тыс")
            if d[0] == "tone" and d[2] not in TONES:
                errs.append(f"{lid} cine: белгісіз реңк {d[2]}")
        a = bt.get("ask")
        if a:
            asks += 1
            if not (0 <= a["ans"] < len(a["opts"])) or len(a["opts"]) < 2 or not a["why"]:
                errs.append(f"{lid} cine: болжам сұрағы толық емес")
    if s.get("kind") == "авторлық":
        chs = [bt["ch"] for bt in s["beats"]]
        if asks != 1 or BO not in chs or BE not in chs or KO not in chs:
            errs.append(f"{lid} cine: авторлық фильмде Бейне, бір Болжа және Көр болуы керек")
        if chs.index(BO) > max(i for i, c in enumerate(chs) if c == KO):
            errs.append(f"{lid} cine: Болжа Көр-ден бұрын болуы керек")
    return errs

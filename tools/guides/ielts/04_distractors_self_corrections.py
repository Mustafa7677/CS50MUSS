def _en(x):
    if isinstance(x, str):
        return x.replace("[[", '<span class="gd-en">').replace("]]", "</span>")
    if isinstance(x, list):
        return [_en(i) for i in x]
    if isinstance(x, dict):
        return {k: _en(v) for k, v in x.items()}
    return x



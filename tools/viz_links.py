def block(rel, items):
    pre = "../" * rel.count("/")
    E = html.escape
    parts = [START, f'<link rel="stylesheet" href="{pre}assets/css/ao-viz.css"><script src="{pre}assets/js/ao-viz.js" defer></script><script src="{pre}assets/js/ao-viz2.js" defer></script>']
    for it in items:
        parts.append(
            f'<section class="aov-embed" aria-label="AO17 интерактивті модель: {E(it["title"])}">'
            f'<p class="aov-kick">AO17 · өзің басқарып көр</p><h2>{E(it["title"])}</h2>'
            f'<div class="aov-3q"><p><b>Неге?</b> {E(it["why"])}</p><p><b>Қалай?</b> {E(it["how"])}</p><p><b>Егер өзгертсек?</b> {E(it["what"])}</p></div>'
            f'<div data-aov="{E(it["t"])}" data-aov-params="{E(json.dumps(it["p"], ensure_ascii=False))}"></div>'
            f'<p class="aov-more"><a href="{pre}academy/models.html#v-{E(it["t"])}">Барлық 20 модель - AO17 интерактивті зертханасы</a></p></section>')
    parts.append(END)
    return "\n      ".join(parts)


def apply():
    changed = 0
    for rel, items in EMBEDS.items():
        fp = ROOT / rel
        if not fp.exists():
            continue
        orig = fp.read_text(encoding="utf-8")
        t = orig
        if START in t:
            a, b = t.index(START), t.index(END) + len(END)
            t = t[:a].rstrip() + "\n" + t[b:].lstrip("\n ")
        new = block(rel, items)
        if '<nav class="pager">' in t:
            i = t.rindex('<nav class="pager">')
            t = t[:i] + new + "\n\n      " + t[i:]
        elif "</article>" in t:
            i = t.rindex("</article>")
            t = t[:i] + new + "\n    " + t[i:]
        else:
            continue
        if t != orig:
            fp.write_text(t, encoding="utf-8")
            changed += 1
    return changed


if __name__ == "__main__":
    print("aov embeds:", apply())
